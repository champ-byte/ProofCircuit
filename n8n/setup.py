"""Set up the optional n8n staff-reminder workflow without UI clicks (PRD 12.1).

    python n8n/setup.py                       # start n8n, import credentials + workflow, publish it
    python n8n/setup.py --write-backend-env   # also add the backend's reminder settings to backend/.env

Secrets live only in n8n/.env and backend/.env (both gitignored). They are generated once, never
printed, and passed to n8n as credentials, never written into the committed workflow export.
Standard library only; needs Docker with the compose plugin.
"""

from __future__ import annotations

import argparse
import json
import secrets
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENV_FILE = HERE / ".env"
BACKEND_ENV = HERE.parent / "backend" / ".env"
COMPOSE = ["docker", "compose", "-f", str(HERE / "docker-compose.yml")]
WORKFLOW = HERE / "staff-reminder.json"
WORKFLOW_ID = "PcStaffReminder1"
WEBHOOK_URL = "http://127.0.0.1:5678/webhook/proofcircuit-staff-reminder"
CREDENTIALS = {  # ids/names must match the references in staff-reminder.json
    "N8N_WEBHOOK_TOKEN": ("PcN8nWebhookAuth", "ProofCircuit trigger token (backend to n8n)"),
    "N8N_SERVICE_TOKEN": ("PcServiceTokenAu", "ProofCircuit service token (n8n to backend)"),
}


def read_env(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            out[key.strip()] = value.strip()
    return out


def ensure_env() -> dict[str, str]:
    env = read_env(ENV_FILE)
    defaults = {
        "N8N_ENCRYPTION_KEY": lambda: secrets.token_urlsafe(32),
        "N8N_WEBHOOK_TOKEN": lambda: secrets.token_urlsafe(32),
        "N8N_SERVICE_TOKEN": lambda: secrets.token_urlsafe(32),
        "BACKEND_BASE_URL": lambda: "http://host.docker.internal:8000",
    }
    added = [k for k in defaults if k not in env]
    for key in added:
        env[key] = defaults[key]()
    if added:
        lines = ["# Generated by n8n/setup.py. Gitignored; never commit or paste these values."]
        lines += [f"{k}={env[k]}" for k in defaults] + [f"{k}={v}" for k, v in env.items() if k not in defaults]
        ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"Wrote {', '.join(added)} to {ENV_FILE} (values not shown).")
    return env


def run(*args: str, quiet: bool = False) -> str:
    result = subprocess.run([*COMPOSE, *args], check=False, capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        sys.exit(f"Command failed ({' '.join(args)}):\n{result.stdout}\n{result.stderr}")
    if not quiet and result.stdout.strip():
        print(result.stdout.strip())
    return result.stdout


def wait_healthy(timeout: float = 120) -> None:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen("http://127.0.0.1:5678/healthz", timeout=3) as resp:
                if resp.status == 200:
                    return
        except (urllib.error.URLError, ConnectionError, TimeoutError):
            pass
        time.sleep(2)
    sys.exit("n8n did not become healthy on http://127.0.0.1:5678/healthz")


def n8n_cli(*args: str) -> str:
    return run("exec", "-T", "n8n", "n8n", *args)


def copy_in(local: Path, remote: str) -> None:
    run("cp", str(local), f"n8n:{remote}", quiet=True)


def remove_in(remote: str) -> None:
    run("exec", "-T", "-u", "root", "n8n", "rm", "-f", remote, quiet=True)  # `docker cp` files are root-owned


def import_credentials(env: dict[str, str]) -> None:
    creds = [
        {
            "id": cred_id,
            "name": name,
            "type": "httpHeaderAuth",
            "data": {"name": "Authorization", "value": f"Bearer {env[key]}"},
        }
        for key, (cred_id, name) in CREDENTIALS.items()
    ]
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "pc-credentials.json"
        path.write_text(json.dumps(creds), encoding="utf-8")
        copy_in(path, "/tmp/pc-credentials.json")
    try:
        n8n_cli("import:credentials", "--input=/tmp/pc-credentials.json")
    finally:
        remove_in("/tmp/pc-credentials.json")


def write_backend_env(env: dict[str, str]) -> None:
    current = read_env(BACKEND_ENV)
    wanted = {
        "REMINDERS_ENABLED": "true",
        "N8N_REMINDER_WEBHOOK_URL": WEBHOOK_URL,
        "N8N_WEBHOOK_TOKEN": env["N8N_WEBHOOK_TOKEN"],
        "N8N_SERVICE_TOKEN": env["N8N_SERVICE_TOKEN"],
    }
    missing = {k: v for k, v in wanted.items() if k not in current}
    if missing:
        with BACKEND_ENV.open("a", encoding="utf-8") as fh:
            fh.write("\n# n8n staff reminders (written by n8n/setup.py)\n")
            fh.writelines(f"{k}={v}\n" for k, v in missing.items())
    print(f"backend/.env: added {', '.join(missing) or 'nothing (already set)'}; restart the backend to apply.")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write-backend-env", action="store_true", help="append reminder settings to backend/.env")
    args = parser.parse_args()

    env = ensure_env()
    run("up", "-d")
    wait_healthy()
    import_credentials(env)
    copy_in(WORKFLOW, "/tmp/staff-reminder.json")
    try:
        n8n_cli("import:workflow", "--input=/tmp/staff-reminder.json")
    finally:
        remove_in("/tmp/staff-reminder.json")
    n8n_cli("publish:workflow", f"--id={WORKFLOW_ID}")
    run("restart", "n8n")  # the running instance registers published webhooks on start
    wait_healthy()
    print(f"Published workflow {WORKFLOW_ID}. Production webhook: {WEBHOOK_URL}")
    if args.write_backend_env:
        write_backend_env(env)
    else:
        print(
            "Backend settings: REMINDERS_ENABLED=true, N8N_REMINDER_WEBHOOK_URL="
            f"{WEBHOOK_URL}, and N8N_WEBHOOK_TOKEN / N8N_SERVICE_TOKEN copied from n8n/.env "
            "(or rerun with --write-backend-env)."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
